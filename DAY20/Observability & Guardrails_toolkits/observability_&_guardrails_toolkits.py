def evaluate_pii_detectors(test_set: List[Dict[str, Any]]):
    print("\n--- Evaluating PII Detectors ---")
    results = collections.defaultdict(lambda: {"TP": 0, "FP": 0, "FN": 0})

    for i, case in enumerate(test_set):
        text = case["text"]
        expected_pii = set(case["expected_pii"])

        _, detected_map = redact(text)
        detected_pii = set()
        for token in detected_map.keys():
            for kind in PII_PATTERNS.keys():
                if token.startswith(f"<{kind}_"):
                    detected_pii.add(kind)
                    break

        print(f"\nTest Case {i+1}:")
        print(f"  Text: {text}")
        print(f"  Expected: {sorted(list(expected_pii))}")
        print(f"  Detected: {sorted(list(detected_pii))}")

        # Update global counts for each PII type
        for pii_type in PII_PATTERNS.keys():
            if pii_type in expected_pii and pii_type in detected_pii:
                results[pii_type]["TP"] += 1
            elif pii_type in expected_pii and pii_type not in detected_pii:
                results[pii_type]["FN"] += 1
            elif pii_type not in expected_pii and pii_type in detected_pii:
                results[pii_type]["FP"] += 1

    print("\n--- PII Detection Metrics (Per Type) ---")
    overall_tp, overall_fp, overall_fn = 0, 0, 0
    for pii_type, counts in results.items():
        tp, fp, fn = counts["TP"], counts["FP"], counts["FN"]
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1_score = (2 * precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0

        print(f"  {pii_type}: ")
        print(f"    TP: {tp}, FP: {fp}, FN: {fn}")
        print(f"    Precision: {precision:.2f}, Recall: {recall:.2f}, F1-Score: {f1_score:.2f}")

        overall_tp += tp
        overall_fp += fp
        overall_fn += fn

    print("\n--- PII Detection Metrics (Overall) ---")
    overall_precision = overall_tp / (overall_tp + overall_fp) if (overall_tp + overall_fp) > 0 else 0.0
    overall_recall = overall_tp / (overall_tp + overall_fn) if (overall_tp + overall_fn) > 0 else 0.0
    overall_f1_score = (2 * overall_precision * overall_recall) / (overall_precision + overall_recall) if (overall_precision + overall_recall) > 0 else 0.0

    print(f"  Overall TP: {overall_tp}, FP: {overall_fp}, FN: {overall_fn}")
    print(f"  Overall Precision: {overall_precision:.2f}")
    print(f"  Overall Recall: {overall_recall:.2f}")
