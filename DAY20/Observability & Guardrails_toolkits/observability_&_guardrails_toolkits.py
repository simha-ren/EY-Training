ADDRESS_RE = re.compile(r"\d{1,5}\s(?:[A-Z][a-z]+\s){1,3}(?:Street|St|Avenue|Ave|Road|Rd|Lane|Ln|Drive|Dr|Plaza|Pl|Court|Ct|Boulevard|Blvd)\.?\s*,?\s*[A-Z][a-z]+\s*,\s*[A-Z]{2}\s*\d{5}(?:-\d{4})?")
