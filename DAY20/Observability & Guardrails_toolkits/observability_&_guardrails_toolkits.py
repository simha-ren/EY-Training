REQUESTS_PER_MINUTE = 60 # 1 request per second
TOKEN_BUCKET_CAPACITY = 5 # Allow a burst of 5 requests
global_token_bucket = TokenBucket(REQUESTS_PER_MINUTE, TOKEN_BUCKET_CAPACITY)

# --- 3. Redefine call_claude with retries and rate limiting ---
MAX_RETRIES = 5
INITIAL_BACKOFF_SECONDS = 0.5
MAX_BACKOFF_SECONDS = 10

def call_claude(prompt: str,
                model: str = MODEL_ROUTINE,
                system: str = "",
                max_tokens: int = 400,
                temperature: float = 0.2) -> LLMResult:
    """Single entry point for all model calls. Returns text + usage telemetry.
       Includes token-bucket rate limiting and exponential backoff retries."""
    t0 = time.perf_counter()
    retries_attempted = 0
    text = ""
    it, ot = 0, 0
    stop = ""
    mock = False
    last_exception = None

    if USE_MOCK:
        text = _mock_response(prompt, model)
        it, ot = _estimate_tokens(system + prompt), _estimate_tokens(text)
        stop = "end_turn"
        mock = True
    else:
        client = anthropic.Anthropic() # Client is lightweight, can be instantiated per call if needed

        for attempt in range(MAX_RETRIES + 1):
            try:
                global_token_bucket.consume(1) # Consume one request token
                if retries_attempted > 0:
                    print(f"Retrying call to {model} (attempt {retries_attempted + 1}/{MAX_RETRIES + 1})")

                msg = client.messages.create(
                    model=model, max_tokens=max_tokens, temperature=temperature,
                    system=system or "You are a helpful assistant.",
                    messages=[{"role": "user", "content": prompt}],
                )
                text = "".join(b.text for b in msg.content if getattr(b, "type", "") == "text")
                it, ot = msg.usage.input_tokens, msg.usage.output_tokens
                stop = msg.stop_reason
                break # Success, exit retry loop
            except (anthropic.RateLimitError, anthropic.APIStatusError) as e:
                last_exception = e
                retries_attempted += 1
                if retries_attempted > MAX_RETRIES:
                    print(f"Max retries ({MAX_RETRIES}) exceeded for {model}. Last error: {e}")
                    raise # Re-raise the last exception if all retries fail

                backoff_time = min(MAX_BACKOFF_SECONDS,
                                   INITIAL_BACKOFF_SECONDS * (2 ** (retries_attempted - 1)))
                jitter = random.uniform(0, INITIAL_BACKOFF_SECONDS) # Add jitter
                sleep_duration = backoff_time + jitter
                print(f"Rate limit or API error for {model}. Retrying in {sleep_duration:.2f}s... (Error: {e})")
                time.sleep(sleep_duration)
            except Exception as e: # Catch other unexpected errors
                last_exception = e
                retries_attempted += 1
                if retries_attempted > MAX_RETRIES:
                    print(f"Max retries ({MAX_RETRIES}) exceeded for {model}. Last error: {e}")
                    raise # Re-raise the last exception if all retries fail
                # For non-rate-limit errors, apply backoff too
                backoff_time = min(MAX_BACKOFF_SECONDS,
                                   INITIAL_BACKOFF_SECONDS * (2 ** (retries_attempted - 1)))
                jitter = random.uniform(0, INITIAL_BACKOFF_SECONDS)
                sleep_duration = backoff_time + jitter
                print(f"Unexpected error for {model}. Retrying in {sleep_duration:.2f}s... (Error: {e})")
                time.sleep(sleep_duration)

    if not text and last_exception: # If mock was false and we failed all retries
        raise last_exception

    dt = (time.perf_counter() - t0) * 1000
    price = PRICES.get(model, {"in": 0, "out": 0})
    cost = it / 1e6 * price["in"] + ot / 1e6 * price["out"]
    return LLMResult(text, model, it, ot, stop, round(dt, 1), round(cost, 6), mock, retries_attempted)


