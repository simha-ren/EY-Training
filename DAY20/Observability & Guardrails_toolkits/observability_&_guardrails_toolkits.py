# 2. Redefine the 'span' context manager to use OpenTelemetry spans.
#    This maintains the API for existing calls like 'with span(...)'.
#    The custom Span dataclass from 'kdnYKobNfpmA' is now effectively superseded.
#    The global SPANS list and _CURRENT dictionary are no longer used for tracing.

# To maintain compatibility with existing code that accesses properties like
# sp.trace_id, sp.span_id, sp.attributes, sp.status, sp.name, and sp.duration_ms,
# we create a wrapper for the OpenTelemetry span.
# Note: duration_ms won't be available until the span ends, and OpenTelemetry handles this internally.
class OTelSpanProxy:
    def __init__(self, otel_span):
        self._otel_span = otel_span
        # OTel span attributes are immutable after creation if not careful.
        # We copy them and provide a method to update the OTel span.
        self.attributes = dict(otel_span.attributes)
        self.name = otel_span.name

    @property
    def trace_id(self):
        return format(self._otel_span.context.trace_id, "x")

    @property
    def span_id(self):
        return format(self._otel_span.context.span_id, "x")

    @property
    def parent_id(self):
        parent_span_context = self._otel_span.parent
        if parent_span_context and parent_span_context.span_id:
            return format(parent_span_context.span_id, "x")
        return None

    @property
    def status(self):
        # OpenTelemetry status codes are different. Map to something similar to original "OK", "ERROR: ExceptionName"
        if self._otel_span.status.status_code == StatusCode.OK:
            return "OK"
        elif self._otel_span.status.status_code == StatusCode.ERROR:
            # The description from OTel status might contain the exception message
            return f"ERROR: {self._otel_span.status.description}"
        return self._otel_span.status.status_code.name # Other status codes

    @property
    def duration_ms(self):
        # OpenTelemetry calculates duration internally on span.end().
        # This proxy cannot directly expose it in real-time unless the OTel span object
        # were to explicitly expose its start/end time. For simplicity and because the
        # original `span` also only had `duration_ms` available after `end_ms` was set,
        # we will return None here, indicating it's handled by the exporter.
        return None

    def update_attributes(self, new_attributes):
        self.attributes.update(new_attributes) # Update internal attributes dict for consistency
        self._otel_span.set_attributes(new_attributes) # Set on the OTel span


@contextlib.contextmanager
def span(name, **attributes):
    with tracer.start_as_current_span(name, attributes=attributes) as otel_span:
        wrapped_span = OTelSpanProxy(otel_span)
        try:
            yield wrapped_span
        except Exception as e:
            otel_span.set_status(Status(StatusCode.ERROR, description=str(e)))
            raise
        finally:
            # OpenTelemetry's context manager handles otel_span.end() automatically
            pass

