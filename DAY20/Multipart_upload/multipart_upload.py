class EventCollector:
    def __init__(self):
        self.events = []
        self.run_start_time = None
        self.total_pipeline_steps = 0
        self.agent_spans = {}
        self.orchestrator_trace_id = None # Store the trace_id for the current run

    def collect(self, event: Event):
        self.events.append(event)
        if event.event_type == "orchestrator_start":
            self.run_start_time = event.timestamp
            self.orchestrator_trace_id = event.trace_id
            self.total_pipeline_steps = event.total_steps # Set total pipeline steps from orchestrator_start
            self.agent_spans = {} # Reset agent_spans for a new run

        if event.event_type == "agent_started": # Renamed from agent_start
            self.agent_spans[event.span_id] = {"agent_name": event.agent_name, "start_time": event.timestamp, "end_time": None, "steps_finished": 0, "total_steps": event.total_steps, "status": "running"}
        elif event.event_type == "agent_progress":
            if event.span_id in self.agent_spans:
                self.agent_spans[event.span_id]["steps_finished"] = event.step
                # total_steps for agent is already set in agent_started, not necessarily updated here.
        elif event.event_type == "agent_completed" or event.event_type == "agent_failed": # Renamed from agent_end/agent_error
            if event.span_id in self.agent_spans:
                self.agent_spans[event.span_id]["end_time"] = event.timestamp
                self.agent_spans[event.span_id]["status"] = event.status
                if event.event_type == "agent_completed": # Ensure steps_finished is accurate for successful completion
                     self.agent_spans[event.span_id]["steps_finished"] = event.total_steps


    def calculate_pipeline_progress(self):
        if self.total_pipeline_steps == 0:
            return 0, 0, 0.0 # percentage, completed steps, total steps

        completed_steps_across_all_agents = 0
        for span_data in self.agent_spans.values():
            completed_steps_across_all_agents += span_data["steps_finished"]

        if self.total_pipeline_steps == 0:
            return 0, completed_steps_across_all_agents, self.total_pipeline_steps

        percent_complete = (completed_steps_across_all_agents / self.total_pipeline_steps) * 100
        return percent_complete, completed_steps_across_all_agents, self.total_pipeline_steps

    def calculate_throughput(self):
        if not self.run_start_time:
            return 0.0

        current_time = datetime.now()
        elapsed_time = (current_time - self.run_start_time).total_seconds()
        if elapsed_time <= 0:
            return 0.0

        _, completed_steps, _ = self.calculate_pipeline_progress()
        return completed_steps / elapsed_time

    def get_per_agent_durations(self):
        durations = {}
        for span_id, data in self.agent_spans.items():
            if data["start_time"] and data["end_time"]:
                duration = (data["end_time"] - data["start_time"]).total_seconds()
                durations[data["agent_name"]] = duration
        return durations

    def get_failed_agent_info(self):
        # Iterate over items to get both span_id (key) and span_data (value)
        for span_id, span_data in self.agent_spans.items():
            if span_data.get("status") == "error":
                # Find the agent_failed event for this span_id to get message and step
                failed_event = next((e for e in self.events if e.span_id == span_id and e.event_type == 'agent_failed'), None)
                if failed_event:
                     return span_data["agent_name"], failed_event.step, failed_event.message
                return span_data["agent_name"], None, None
        return None, None, None


