class EventCollector:
    def __init__(self):
        self.events = []
        self.run_start_time = None
        self.total_pipeline_steps = 0
        self.agent_spans = {}

    def collect(self, event: Event):
        self.events.append(event)
        if event.event_type == "orchestrator_start":
            self.run_start_time = event.timestamp
            # Calculate total pipeline steps based on the agents in the orchestrator
            # This assumes the orchestrator is initialized with the full list of agents
            # For a more robust solution, Orchestrator could emit this total.
            # For now, we'll infer it from the first agent_progress events or Orchestrator initialization.

        if event.event_type == "agent_progress" and event.trace_id not in self.agent_spans:
             # This is a temporary way to get total_pipeline_steps if not set by orchestrator
            # A better way would be for Orchestrator to emit this in its start event
            all_agents_steps = {e.agent_name: e.total_steps for e in self.events if e.event_type == "agent_progress"}
            self.total_pipeline_steps = sum(all_agents_steps.values())

        if event.event_type == "agent_start":
            self.agent_spans[event.span_id] = {"agent_name": event.agent_name, "start_time": event.timestamp, "end_time": None, "steps_finished": 0, "total_steps": 0}
        elif event.event_type == "agent_progress":
            if event.span_id in self.agent_spans:
                self.agent_spans[event.span_id]["steps_finished"] = event.step
                self.agent_spans[event.span_id]["total_steps"] = event.total_steps
        elif event.event_type == "agent_end" or event.event_type == "agent_error":
            if event.span_id in self.agent_spans:
                self.agent_spans[event.span_id]["end_time"] = event.timestamp
                if event.event_type == "agent_end": # Ensure steps_finished is accurate for successful completion
                     self.agent_spans[event.span_id]["steps_finished"] = event.total_steps


    def calculate_pipeline_progress(self):
        if not self.total_pipeline_steps:
            return 0, 0, 0.0 # percentage, completed steps, total steps

        completed_steps_across_all_agents = 0
        for span_data in self.agent_spans.values():
            completed_steps_across_all_agents += span_data["steps_finished"]

        percent_complete = (completed_steps_across_all_agents / self.total_pipeline_steps) * 100
        return percent_complete, completed_steps_across_all_agents, self.total_pipeline_steps

    def calculate_throughput(self):
        if not self.run_start_time:
            return 0.0

        current_time = datetime.now()
        elapsed_time = (current_time - self.run_start_time).total_seconds()
        if elapsed_time == 0:
            return 0.0

        _, completed_steps, _ = self.calculate_pipeline_progress()
        return completed_steps / elapsed_time

    def get_per_agent_durations(self):
        durations = {}
        for span_id, data in self.agent_spans.items():
            if data["start_time"] and data["end_time"]:
                duration = (data["end_time"] - data["start_time"]).total_seconds()
                durations[data["agent_name"]] = duration
        return durations

