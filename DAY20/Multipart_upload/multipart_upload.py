import random
import time
import uuid
import json
from dataclasses import dataclass, field, asdict
from datetime import datetime, timedelta
import math

@dataclass
class Event:
    timestamp: datetime = field(default_factory=datetime.now)
    event_type: str = "" # Maps to 'event' in JSON output
    agent_name: str = "" # Maps to 'agent' in JSON output
    trace_id: str = ""
    span_id: str = ""
    duration: float = 0.0
    status: str = ""
    message: str = ""
    step: int = 0
    total_steps: int = 0

    def to_json_dict(self):
        # Convert dataclass to dict, handle datetime, and rename fields as requested
        data = asdict(self)
        data['timestamp'] = self.timestamp.isoformat()
        data['event'] = data.pop('event_type')
        data['agent'] = data.pop('agent_name')
        return data

class Agent:
    """A simulated agent that does N steps of work. Pure simulation - no LLM, no network."""

    def __init__(self, name, steps, fail_at_step=None):
        self.name = name
        self.steps = steps
        self.fail_at_step = fail_at_step # set to an int to force a deterministic failure

    def run(self, listener, trace_id, span_id):
        start_time = time.time()
        listener(Event(event_type="agent_started", agent_name=self.name, trace_id=trace_id, span_id=span_id, message="Starting agent run.", total_steps=self.steps))

        try:
            # Throttling logic for agent_progress events
            progress_thresholds = [0.25, 0.50, 0.75]
            last_reported_threshold_idx = -1 # Index of the last threshold reported

            for step in range(1, self.steps + 1):
                step_start_time = time.time()
                time.sleep(random.uniform(0.05, 0.2)) # simulate work / latency

                if self.fail_at_step and step == self.fail_at_step:
                    raise RuntimeError(f"{self.name} failed at step {step}")

                current_progress_percentage = step / self.steps
                for i, threshold in enumerate(progress_thresholds):
                    if current_progress_percentage >= threshold and i > last_reported_threshold_idx:
                        step_duration = time.time() - step_start_time
                        listener(Event(event_type="agent_progress", agent_name=self.name, trace_id=trace_id, span_id=span_id,
                                       duration=step_duration, status=f"step {step}/{self.steps}",
                                       message=f"{self.name}: {int(threshold*100)}% complete ({step}/{self.steps})",
                                       step=step, total_steps=self.steps))
                        last_reported_threshold_idx = i
                        break # Only report the highest reached threshold at any point

            duration = time.time() - start_time
            listener(Event(event_type="agent_completed", agent_name=self.name, trace_id=trace_id, span_id=span_id, duration=duration, status="success", message="Agent run completed.", step=self.steps, total_steps=self.steps))
        except Exception as e:
            duration = time.time() - start_time
            listener(Event(event_type="agent_failed", agent_name=self.name, trace_id=trace_id, span_id=span_id, duration=duration, status="error", message=f"Agent run failed: {e}", step=step, total_steps=self.steps))
            raise # Re-raise the exception to propagate failure


