def agent_turn_compacted(user_text, max_steps=6, verbose=True, conversation_limit=8, compaction_amount=4):
    """
    Handles an agent turn with conversation history compaction.
    When history length exceeds `conversation_limit + compaction_amount`,
    it summarizes the oldest `compaction_amount` turns.
    `conversation_limit` is the desired maximum length of history after compaction.
    `compaction_amount` is how many old turns to summarize into one.
    """
    mem.append_turn('user', user_text) # Append the new user turn

    # Load all current messages from memory
    current_messages_from_redis = mem.load_history()

    # Check if compaction is needed
    if len(current_messages_from_redis) > conversation_limit + compaction_amount:
        if verbose: print(f'  → History length {len(current_messages_from_redis)} exceeds compaction trigger ({conversation_limit + compaction_amount}). Compacting...')

        # Identify the oldest messages to summarize
        # We take the oldest 'compaction_amount' messages
        messages_to_summarize = current_messages_from_redis[0 : compaction_amount]

        # Generate summary (Anthropic client will be instantiated inside if LIVE)
        summary_message = summarize_messages(messages_to_summarize)

        # Reconstruct the history list: [summary_message] + [remaining recent messages]
        new_history_for_redis = [summary_message] + current_messages_from_redis[compaction_amount:]

        # Clear existing history in Redis
        mem.r.delete(mem.h_key)

        # Re-append the new, compacted history to Redis
        for msg in new_history_for_redis:
            mem.r.rpush(mem.h_key, json.dumps(msg))

        if verbose: print(f'  → History compacted. New length: {len(mem.load_history())} turns.')

        # Use the newly compacted history for the current turn's LLM call
        messages_for_llm = mem.load_history()
    else:
        # No compaction needed, use the full history
        messages_for_llm = current_messages_from_redis

    # --- Remainder of original agent_turn logic, using messages_for_llm ---
    if not LIVE:
        # ---- offline mock: pretend the model asked for get_order once ----
        if verbose: print('… (mock) model requests get_order A1001')
        out, _ = run_tool_v3('get_order', {'order_id': 'A1001'}) # Use run_tool_v3
        reply = f'(mock) Order A1001 is {out.get("status", "?")}.'
        mem.append_turn('assistant', reply)
