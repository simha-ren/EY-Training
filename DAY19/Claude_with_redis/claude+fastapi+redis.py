"""2.TTL & a forget tool. Add a forget_fact(key) tool and give facts a TTL via set_fact(..., ttl_seconds=...). Show that an expired fact returns None."""

import json, time, fakeredis

# Redefine the RedisMemory class to support individual fact TTL and deletion.
# This changes the underlying storage for facts from a single Redis Hash to individual Redis String keys.
class RedisMemory:
    def __init__(self, r, session_id: str, history_limit: int = 40):
        self.r = r # The fakeredis.FakeStrictRedis instance
        self.sid = session_id
        self.history_limit = history_limit
        self.h_key = f'hist:{session_id}' # For conversation history (Redis List)
        # Facts will now be stored as individual keys: fact:<session_id>:<key>

    # ---- short-term: conversation turns (unchanged) ----
    def append_turn(self, role: str, content):
        self.r.rpush(self.h_key, json.dumps({'role': role, 'content': content}))
        self.r.ltrim(self.h_key, -self.history_limit, -1)  # keep only the tail

    def load_history(self):
        return [json.loads(x) for x in self.r.lrange(self.h_key, 0, -1)]

    # ---- long-term: durable facts (modified for individual TTL) ----
    def set_fact(self, key: str, value: str, ttl_seconds: int | None = None):
        fact_redis_key = f'fact:{self.sid}:{key}'
        # Use Redis SET command with EX (expire) option for individual key TTL
        self.r.set(fact_redis_key, value, ex=ttl_seconds)

    def get_fact(self, key: str):
        fact_redis_key = f'fact:{self.sid}:{key}'
        v = self.r.get(fact_redis_key)
        # Redis GET returns bytes or None if key does not exist or has expired
        return v.decode() if isinstance(v, bytes) else v

    def delete_fact(self, key: str):
        fact_redis_key = f'fact:{self.sid}:{key}'
        self.r.delete(fact_redis_key)
        return {'ok': True, 'deleted': key}

    def all_facts(self):
        # To get all facts, we need to find keys matching the pattern and then retrieve their values
        fact_keys = self.r.keys(f'fact:{self.sid}:*')
        facts = {}
        for k_bytes in fact_keys:
            # Extract original key name from 'fact:<session_id>:<key>'
            k_str = ':'.join(k_bytes.decode().split(':')[2:])
            v_bytes = self.r.get(k_bytes) # Get value for the found key
            if v_bytes is not None: # Ensure the key hasn't expired between keys() and get()
                facts[k_str] = v_bytes.decode()
        return facts

