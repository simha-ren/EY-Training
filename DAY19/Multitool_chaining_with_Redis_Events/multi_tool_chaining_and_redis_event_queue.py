"""3.Orchestrator-worker split. Move run_worker() into a background threading.Thread loop so the agent never calls it directly; the queue truly decouples them."""

import threading
import time

# Flag to signal the worker thread to stop
worker_stop_event = threading.Event()

def worker_thread_loop():
    """Continuously runs the email worker until a stop event is set."""
    print("[Worker Thread]: Starting background email worker...")
    while not worker_stop_event.is_set():
        try:
            processed_count = run_worker() # run_worker is already defined
            if processed_count > 0:
                print(f"[Worker Thread]: Processed {processed_count} email job(s).")
        except Exception as e:
            print(f"[Worker Thread]: Error in worker: {e}")
        # Wait for a short period or until signaled to stop
        worker_stop_event.wait(timeout=1) # Check every 1 second
    print("[Worker Thread]: Background email worker stopped.")

# Start the worker thread
worker_thread = threading.Thread(target=worker_thread_loop, daemon=True)
worker_thread.start()

# Function to stop the worker thread (optional, for cleanup if needed)
def stop_background_worker():
    print("Signaling background worker to stop...")
    worker_stop_event.set()
    worker_thread.join(timeout=5) # Give it some time to finish
    if worker_thread.is_alive():
        print("Warning: Worker thread did not stop gracefully.")

# Register the stop function to run on exit (e.g., when Colab runtime stops)
import atexit
atexit.register(stop_background_worker)

