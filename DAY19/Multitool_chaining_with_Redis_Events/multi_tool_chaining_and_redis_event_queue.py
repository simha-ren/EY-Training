    max_tool_len = max(len(t['tool']) for t in TOOL_TRACES) if TOOL_TRACES else 4
    max_args_len = max(len(str(t['args'])) for t in TOOL_TRACES) if TOOL_TRACES else 4

    # Ensure minimum width for readability
    max_tool_len = max(max_tool_len, len('Tool'))
    max_args_len = max(max_args_len, len('Args'))

