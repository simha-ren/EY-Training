# Redefine run_tool with tracing capabilities
def run_tool(name, args):
    start_time = time.perf_counter()
    out, is_err = {}, True # Initialize output and error status

    fn = DISPATCH.get(name) # DISPATCH is expected to be a global variable from previous cells
    if not fn:
        out = {'error': f'unknown tool {name}'}
        is_err = True
    else:
        try:
            out = fn(**args)
            # A tool result is considered an error if it's a dict and contains an 'error' key
            is_err = isinstance(out, dict) and 'error' in out
        except Exception as e:
            out = {'error': repr(e)}
            is_err = True

    end_time = time.perf_counter()
    elapsed_ms = round((end_time - start_time) * 1000, 2)

    TOOL_TRACES.append({'tool': name, 'args': args, 'ms': elapsed_ms, 'ok': not is_err})

    return out, is_err

