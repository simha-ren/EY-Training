# Constants for DLQ and retries
DLQ_STREAM = 'emails:dlq'
MAX_RETRIES = 3

# Helper for email validation
def is_valid_email(email):
    return '@' in email and '.' in email.split('@')[-1]

# --- Modified enqueue_email function (from JGSxnVtPVZSZ) ---
def enqueue_email(to, subject, body, retries=0):
    job_id = uuid.uuid4().hex[:8]
    r.xadd(STREAM, {'job_id': job_id, 'to': to, 'subject': subject, 'body': body, 'retries': str(retries)})
    r.set(f'jobresult:{job_id}', 'queued')
    return job_id

# --- Modified run_worker function (from XkU3qkSLViNs) ---
def run_worker(max_msgs=10):
    processed = 0
    resp = r.xreadgroup(GROUP, 'worker-1', {STREAM: '>'}, count=max_msgs, block=500) # Added block to avoid busy-waiting
    for _stream, msgs in resp or []:
        for msg_id, fields in msgs:
            f = {k.decode(): v.decode() for k, v in fields.items()}
            job_id = f['job_id']
            to = f['to']
            current_retries = int(f.get('retries', 0))

            # Simulate email sending failure based on invalid email address
            if not is_valid_email(to):
                current_retries += 1
                if current_retries < MAX_RETRIES:
                    # Re-enqueue with incremented retry count
                    r.xadd(STREAM, {**f, 'retries': str(current_retries)})
                    r.set(f'jobresult:{job_id}', f'retrying (attempt {current_retries}/{MAX_RETRIES})')
                    print(f"Job {job_id} for '{to}' retrying: {current_retries}/{MAX_RETRIES}")
                else:
                    # Move to DLQ
                    r.xadd(DLQ_STREAM, f)
                    r.set(f'jobresult:{job_id}', 'dead-lettered')
                    print(f"Job {job_id} for '{to}' dead-lettered after {current_retries} retries")
                r.xack(STREAM, GROUP, msg_id) # Acknowledge from main stream
            else:
                # --- Real email sending logic would go here ---
                # For now, just mark as sent
                r.set(f"jobresult:{job_id}", 'sent')
                r.xack(STREAM, GROUP, msg_id)
                processed += 1
                print(f"Job {job_id} for '{to}' sent")
    return processed

# --- New tool to inspect DLQ ---
def inspect_dlq(count=10):
    messages = []
    try:
        # Read messages from the DLQ stream
        resp = r.xrange(DLQ_STREAM, count=count)
        for msg_id, fields in resp:
            messages.append({k.decode(): v.decode() for k, v in fields.items()})
    except Exception as e:
        # DLQ_STREAM might not exist if no messages are dead-lettered yet
        if 'no such key' in str(e).lower():
            return []
        else:
            raise
    return messages

