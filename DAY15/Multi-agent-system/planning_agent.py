# Define a wrapper for a local HuggingFace model to be compatible with LangChain's .invoke()
class HuggingFaceLocalLLM:
    def __init__(self, model_name: str):
        print(f"Loading tokenizer: {model_name}...")
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)

        print(f"Loading model: {model_name}...")
        self.model = AutoModelForCausalLM.from_pretrained(model_name, device_map="auto", torch_dtype=torch.bfloat16, trust_remote_code=True)

        print(f"Loaded model type: {type(self.model)}")
        print(f"Model config type: {self.model.config.model_type}")
        print(f"Model max position embeddings: {getattr(self.model.config, 'max_position_embeddings', 'N/A')}")

        max_seq_len = getattr(self.model.config, 'max_position_embeddings', self.tokenizer.model_max_length)
        if max_seq_len is None:
            max_seq_len = 4096
        if max_seq_len > 8192:
            max_seq_len = 8192

        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token

        self.pipeline = pipeline(
            "text-generation",
            model=self.model,
            tokenizer=self.tokenizer,
            max_new_tokens=512,
            max_length=max_seq_len,
            temperature=0.7,
            truncation=True,
            do_sample=True,
            top_p=0.95,
            repetition_penalty=1.2
            # Removed: device=self.model.device because device_map="auto" is used
        )
        print(f"Model {model_name} loaded and pipeline initialized with max_length={max_seq_len}.")

    def invoke(self, messages: List[Any], **kwargs) -> Any:
        prompt_messages = []
        for msg in messages:
            if isinstance(msg, SystemMessage):
                prompt_messages.append({"role": "system", "content": msg.content})
            elif isinstance(msg, HumanMessage):
                prompt_messages.append({"role": "user", "content": msg.content})

        if hasattr(self.tokenizer, 'apply_chat_template') and self.tokenizer.chat_template:
            prompt = self.tokenizer.apply_chat_template(prompt_messages, tokenize=False, add_generation_prompt=True)
        else:
            prompt = ""
            for msg in messages:
                if isinstance(msg, SystemMessage):
                    prompt += f"System: {msg.content}\n"
                elif isinstance(msg, HumanMessage):
                    prompt += f"User: {msg.content}\n"
                else:
                    prompt += f"{msg.content}\n"
            prompt += "Assistant: "

        response = self.pipeline(prompt, **kwargs)
        generated_text = response[0]['generated_text'][len(prompt):].strip()

        class MockResponse:
            def __init__(self, content):
                self.content = content
        return MockResponse(generated_text)

